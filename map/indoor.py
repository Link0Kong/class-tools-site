"""Rooms and schematic floor geometry transcribed from the November 27 signs."""

CLASSROOM = '多媒体教室'


def rect(x, y, width, height):
    return [[x, y], [x + width, y], [x + width, y + height], [x, y + height]]


def room(code, name=CLASSROOM, polygon=None):
    code = str(code)
    if code[:1] in ('1', '2') and len(code) in (4, 5):
        code = '0' + code
    result = {'code': code, 'name': name}
    if polygon:
        result['p'] = polygon
    return result


def run(codes, x, y, width, height, names=None):
    names = names or {}
    step = width / len(codes)
    return [room(code, names.get(code, CLASSROOM),
                 rect(round(x + i * step), y, round(step) - 1, height))
            for i, code in enumerate(codes) if code]


def directory(groups):
    rooms = []
    for name, codes in groups.items():
        for code in codes.split():
            start, sep, end = code.partition('~')
            if not sep:
                rooms.append(room(start, name))
                continue
            first = int(start[-2:])
            last = int(end)
            rooms.extend(room(start[:-2] + f'{suffix:02}', name) for suffix in range(first, last + 1))
    return rooms


def merge(*groups):
    rooms = {}
    for group in groups:
        for entry in group:
            previous = rooms.get(entry['code'])
            if not previous or not previous.get('p') or entry.get('p'):
                rooms[entry['code']] = entry
    return list(rooms.values())


def floor(number, rooms, outline=None, facilities=None, court=None):
    result = {'level': number, 'rooms': sorted(rooms, key=lambda entry: entry['code'])}
    if outline:
        result.update({'size': [620, 320], 'outline': outline, 'facilities': facilities, 'court': court})
    return result


def facility(name, x, y, width, height):
    return {'name': name, 'p': rect(x, y, width, height)}


def zi_floor(level, top, bottom, left, slant, notes, names=None, hall=None):
    names = names or {}
    has_annex = level <= 3
    upper_end = [[588, 100], [557, 120], [514, 120], [483, 101], [483, 79]] if has_annex else [[483, 79]]
    outline = [[22, 22], [588 if has_annex else 483, 22], *upper_end,
               [377, 79], [377, 132], [427, 162], [338, 301], [37, 301],
               [37, 183 if level == 5 else 126], [64, 183 if level == 5 else 126], [64, 79], [22, 79]]
    rooms = run(top, 54, 24, 367, 37, names)
    rooms += run(bottom, 102, 250, 208, 47, names)
    rooms += [room(code, names.get(code, CLASSROOM), rect(39, y, 53, h)) for code, y, h in left]
    angled = [[[375, 135], [423, 162], [399, 202], [351, 175]],
              [[350, 177], [398, 204], [375, 243], [327, 216]],
              [[326, 218], [374, 245], [358, 271], [312, 245]]]
    rooms += [room(code, names.get(code, CLASSROOM), polygon) for code, polygon in zip(slant, angled) if code]
    if hall:
        rooms.append(room(hall, names[hall], [[492, 25], [585, 25], [585, 98], [555, 116], [516, 116], [492, 100]]))
    facilities = [facility('楼梯', 25, 25, 26, 28), facility('楼梯', 78, 257, 20, 38),
                  facility('楼梯', 313, 263, 26, 31), facility('卫生间', 445, 25, 35, 35)]
    court = [[94, 79], [370, 79], [370, 132], [303, 239], [94, 239]]
    return floor(level, merge(directory(notes), rooms), outline, facilities, court)


def hou_floor(level, top, bottom, side, notes, names=None):
    names = names or {}
    left_annex = [[95, 86], [95, 24]] if level == 2 else [[140, 86], [140, 42]]
    outline = [left_annex[-1], [575, left_annex[-1][1]], [575, 98], [537, 98], [537, 213],
               [575, 213], [575, 266], [515, 266], [515, 301], [336, 301], [336, 281],
               [32, 281], [32, 216], [174, 216], [174, 86], left_annex[0]]
    rooms = run(top, 224, left_annex[-1][1] + 2, 270, 46, names)
    rooms += run(bottom, 34, 239, 474, 39, names)
    rooms += [room(code, names.get(code, CLASSROOM), rect(x, y, w, h)) for code, x, y, w, h in side]
    facilities = [facility('楼梯', 194, 47, 28, 42), facility('楼梯', 546, 43, 27, 45),
                  facility('楼梯', 36, 218, 35, 19), facility('楼梯', 544, 230, 29, 33)]
    if level != 5:
        facilities.append(facility('卫生间', 73, 218, 72, 19))
    court = [[205, 101], [500, 101], [500, 226], [348, 226], [330, 215], [205, 215]]
    return floor(level, merge(directory(notes), rooms), outline, facilities, court)


